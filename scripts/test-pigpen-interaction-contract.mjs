import assert from 'node:assert/strict';
import { normalizeQuestion, validateQuestionAnswer, stripPrivateGenerationFields } from '../public/js/escape-room-creator-model.mjs';
import { closeGeneratedAnswer, questionInteractionIssues } from '../public/js/escape-room-question-policy.mjs';
import { buildPreviewDocument } from '../public/js/escape-room-package-builder.mjs';
const multimedia = normalizeQuestion({ ...closeGeneratedAnswer({ respuesta_correcta: 'Una célula vegetal', opciones: ['Una célula vegetal','Un mineral','Un animal','Una estrella'] }, 'multimedia'), tipo_interaccion: 'multimedia', media: {tipo:'imagen',url:'https://example.com/image.png'} });
assert.equal(multimedia.interaction_contract_version, 1);
assert.deepEqual(questionInteractionIssues(multimedia, {requireMedia:true}), []);
assert.ok(questionInteractionIssues({...multimedia, media:null}, {requireMedia:true}).length);
assert.ok(questionInteractionIssues({...multimedia, opciones:['A','A','B','C']}).length);
assert.ok(questionInteractionIssues({...multimedia, respuesta_correcta:'Fuera'}).length);
const blank = normalizeQuestion({tipo_interaccion:'completar_espacio', interaction_contract_version:1, subtipo_respuesta:'frase_corta', texto_con_hueco:'La ___ tiene cloroplastos.', respuesta_correcta:'célula vegetal'});
assert.deepEqual(questionInteractionIssues(blank), []);
assert.equal(validateQuestionAnswer(blank,'célula vegetal'),true);
assert.equal(validateQuestionAnswer(blank,'mineral'),false);
for (const texto_con_hueco of ['Sin hueco','___ y ___']) assert.ok(questionInteractionIssues({...blank,texto_con_hueco}).length);
assert.ok(questionInteractionIssues({...blank,reto:'Selecciona una opción'}).length);
const old = normalizeQuestion({tipo_interaccion:'multimedia',subtipo_respuesta:'frase_libre'});
assert.equal(old.interaction_contract_version,0);
assert.equal(validateQuestionAnswer(old,'Texto histórico'),true);
const project = {titulo:'Contrato',misiones:[{id:'room',titulo:'Sala',preguntas:[multimedia,blank,old]}]};
assert.equal(stripPrivateGenerationFields(project).misiones[0].preguntas[0].interaction_contract_version,1);
assert.ok(buildPreviewDocument(project).includes('interaction_contract_version'));
console.log('Interaction contracts OK');
